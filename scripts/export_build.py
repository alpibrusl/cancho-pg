#!/usr/bin/env python3
"""Build `pg-export` for one database: the network is one `host:port` and the password is one file (docs/design.md section 11).

    python3 scripts/export_build.py --host db.internal --port 5432 [--password-file /run/secrets/pg] [--out build/pg-export-db]
                                    [--gen build/gen] [--manifest FILE [--check]] [--cancho PATH]
    pg-export-db <user> <database> <sql> [max_rows [max_bytes]]

A capability's bound is a literal (cancho `docs/capability-budget.md`), so the host, the port and the password path cannot be
flags: this script writes the variant's `main` with them as literals, builds it with `tools/pgexport/core.cho` and `src/pg.cho`,
and derives the authority row with `cancho authority`. It fails, and removes the binary, if that row is not exactly what section 11
says: `bounded: true` and the labels of the generic build with `net_out("<host>:<port>")` instead of `net_out("")`, and
`fs_read("<password file>")` added when there is one. `--manifest FILE` writes that row (the bound, the labels, the foreign
symbols); with `--check` it compares with the file instead and fails if they differ.

Every input is validated before a file is written, so a bad one is an error of this script and never a source that compiles to
a wider row.
"""
import argparse
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HOST = re.compile(r"^[A-Za-z0-9]([A-Za-z0-9.-]{0,251}[A-Za-z0-9])?$")
PATH = re.compile(r"^/[A-Za-z0-9_./-]+$")

BASE_LABELS = [("args", None), ("conn_read", None), ("conn_write", None), ("err_write", None), ("fs_read", "/dev/urandom"),
               ("heap", None), ("io_write", None)]


def fail(message):
    sys.exit("export_build: " + message)


def validate(host, port, password_file):
    if not HOST.match(host) or ".." in host:
        fail("--host %r is not a host name or an IPv4 address (letters, digits, dots and hyphens; no wildcard, no brackets)" % host)
    if not 1 <= port <= 65535:
        fail("--port %d is not from 1 to 65535" % port)
    if password_file is not None:
        if not PATH.match(password_file):
            fail("--password-file %r is not an absolute path of plain characters" % password_file)
        if any(part in ("", ".", "..") for part in password_file.split("/")[1:]):
            fail("--password-file %r has an empty, `.` or `..` part" % password_file)
        if password_file == "/dev/urandom" or password_file.startswith("/dev/urandom/"):
            fail("--password-file may not be /dev/urandom or under it")


def read_password_fn(path):
    return '''
// The password: the file's contents, at most 1,024 bytes, one trailing newline removed. Status 1 if the file cannot be read,
// is empty or is longer than that. The content and the path are never printed.
fn read_password[&h, &f](heap: &!h Heap, fs: &f Fs("%(p)s")) -> [heap, fs_read("%(p)s")] (buffer.Buffer, int) {
    var out = buffer.empty(heap, 1);
    var status = 0;
    region a {
        let raw = alloc_slice[a](1026, byte_of(0));
        let got = fs_read(fs, "%(p)s", raw);
        if got < 1 || got > 1024 {
            status = 1;
        } else {
            var n = got;
            if int_of(raw[n - 1]) == 10 {
                n = n - 1;
                if n > 0 && int_of(raw[n - 1]) == 13 {
                    n = n - 1;
                }
            }
            if n < 1 {
                status = 1;
            } else {
                out = buffer.append(heap, out, raw[0..n]);
            }
        }
    }
    return (out, status);
}
''' % {"p": path}


def source(host, port, password_file):
    narrow_fs = ('let (rng, pwfs) = narrow(fs, "/dev/urandom", "%s");' % password_file) if password_file else 'let rng = narrow(fs, "/dev/urandom");'
    release_pw = "    release(pwfs);\n" if password_file else ""
    if password_file:
        secret = '''                var secret = buffer.empty(h, 1);
                var pst = 0;
                borrow pwfs as &pf in {
                    let (b, st) = read_password(h, pf);
                    buffer.drop(h, secret);
                    secret = b;
                    pst = st;
                }
'''
    else:
        secret = '''                var secret = buffer.empty(h, 1);
                var pst = 0;
'''
    return '''edition 5;

import std.buffer;
import std.io;
import pg;
import pgexport;

// GENERATED by scripts/export_build.py -- do not edit. The program of docs/design.md section 11: `pg-export` for the one
// database %(bound)s%(pwnote)s.
//
//     pg-export <user> <database> <sql> [max_rows [max_bytes]]
%(readfn)s
fn main(world: World) -> [] int {
    let Split { io, ffi, fs, heap, args, net, clock } = split(world);
    release(ffi);
    release(clock);
    %(narrow_fs)s
    let db = narrow(net, "%(bound)s");
    var status = 2;
    borrow args as &g in {
        if arg_count(g) >= 4 && arg_count(g) <= 6 {
            var rows_text = "";
            var bytes_text = "";
            if arg_count(g) > 4 {
                rows_text = arg(g, 4);
            }
            if arg_count(g) > 5 {
                bytes_text = arg(g, 5);
            }
            borrow mut heap as &!h in {
%(secret)s                if pst != 0 {
                    borrow mut io as &!i in {
                        pgexport.complain(i, "pg-export.password-file", "the password file cannot be read, is empty, or is over 1024 bytes");
                    }
                    status = 1;
                } else {
                    borrow secret as &sr in {
                        borrow rng as &z in {
                            borrow db as &nn in {
                                match tcp_connect(nn, "%(host)s", %(port)d) {
                                    Dialed::Ok(c) => {
                                        var conn = c;
                                        borrow mut conn as &!ch in {
                                            borrow mut io as &!i in {
                                                status = pgexport.run_export(h, i, ch, z, arg(g, 1), arg(g, 2), buffer.bytes(sr), arg(g, 3), rows_text, bytes_text);
                                            }
                                        }
                                        conn_close(conn);
                                    }
                                    Dialed::Failed(e) => {
                                        borrow mut io as &!i in {
                                            pgexport.complain(i, "pg-export.connect", "cannot connect to the database");
                                        }
                                        status = 1;
                                    }
                                }
                            }
                        }
                    }
                }
                buffer.drop(h, secret);
            }
        } else {
            borrow mut io as &!i in {
                pgexport.complain(i, "pg-export.usage", "pg-export <user> <database> <sql> [max_rows [max_bytes]]");
            }
        }
    }
    release(rng);
%(release_pw)s    release(db);
    release(args);
    release(io);
    release(heap);
    return status;
}
''' % {"bound": "%s:%d" % (host, port), "host": host, "port": port, "pwnote": (", password from " + password_file) if password_file else ", no password",
       "readfn": read_password_fn(password_file) if password_file else "", "narrow_fs": narrow_fs, "secret": secret, "release_pw": release_pw}


def derive(cancho, files):
    p = subprocess.run([cancho, "authority", *files, "--std", "--output", "json"], capture_output=True, text=True, cwd=ROOT)
    if p.returncode != 0:
        fail("cancho authority failed:\n" + p.stdout + p.stderr)
    row = json.loads(p.stdout)
    labels = sorted((l["name"], l["argument"]) for l in row["labels"])
    return {"bounded": row["bounded"], "labels": [list(l) for l in labels], "foreign_symbols": row["foreign_symbols"]}


def expected(host, port, password_file):
    labels = list(BASE_LABELS) + [("net_out", "%s:%d" % (host, port))]
    if password_file:
        labels.append(("fs_read", password_file))
    return sorted(labels, key=lambda l: (l[0], l[1] or ""))


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--host", required=True)
    ap.add_argument("--port", required=True, type=int)
    ap.add_argument("--password-file")
    ap.add_argument("--out")
    ap.add_argument("--gen", default=os.path.join(ROOT, "build", "gen"))
    ap.add_argument("--manifest")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--cancho", default=os.environ.get("CANCHO", "cancho"))
    a = ap.parse_args()
    validate(a.host, a.port, a.password_file)
    if a.check and not a.manifest:
        fail("--check needs --manifest FILE")
    tag = re.sub(r"[^A-Za-z0-9]", "_", "%s_%d" % (a.host, a.port))
    out = a.out or os.path.join(ROOT, "build", "pg-export-" + tag)
    os.makedirs(a.gen, exist_ok=True)
    main_cho = os.path.join(a.gen, "pgexport_main_%s.cho" % tag)
    with open(main_cho, "w") as f:
        f.write(source(a.host, a.port, a.password_file))
    files = [main_cho, os.path.join(ROOT, "tools", "pgexport", "core.cho"), os.path.join(ROOT, "src", "pg.cho")]
    row = derive(a.cancho, files)
    want = [list(l) for l in expected(a.host, a.port, a.password_file)]
    if not row["bounded"] or row["labels"] != want or row["foreign_symbols"] != []:
        fail("the derived authority row is not the one section 11 requires.\n  required: bounded, %s\n  derived:  bounded=%s, %s"
             % (want, row["bounded"], row["labels"]))
    if a.manifest:
        text = json.dumps(row, indent=2, sort_keys=True) + "\n"
        if a.check:
            if not os.path.exists(a.manifest) or open(a.manifest).read() != text:
                fail("%s is not the row derived for this variant; regenerate it without --check and review the diff" % a.manifest)
        else:
            os.makedirs(os.path.dirname(os.path.abspath(a.manifest)), exist_ok=True)
            open(a.manifest, "w").write(text)
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    p = subprocess.run([a.cancho, "build", "--std", *files, "-o", out], capture_output=True, text=True, cwd=ROOT)
    if p.returncode != 0:
        fail("cancho build failed:\n" + p.stdout + p.stderr)
    print("built %s: network %s:%d only%s" % (out, a.host, a.port, (", password from %s" % a.password_file) if a.password_file else ", no password"))
    if not re.match(r"^\d+\.\d+\.\d+\.\d+$", a.host):
        print("note: %r is a name; the row names it, and what it resolves to is the resolver's answer at run time (use an IP literal for the tighter claim)" % a.host)


main()
